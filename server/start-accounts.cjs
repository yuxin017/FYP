'use strict';
const {createAccountService}=require('./account_service.cjs');
const {auth,db,projectId,accessToken,sharedFirestore,FieldValue}=require('./firebase_account_adapter.cjs');
const {createReservationHandlers}=require('../functions/src/reservations');
const {createVisitHandlers}=require('../functions/src/visits');
const {createGroupHandlers}=require('../functions/src/groups');
const {createPhotoHandlers}=require('../functions/src/photos');
const {PythonWorker}=require('./python_worker.cjs');
const {createParkManagementHandlers}=require('../functions/src/park_management');
const {createQueueJobs}=require('../functions/src/queue_jobs');
const {mailReady,loadServiceConfig}=require('./service_config.cjs');
const {createProjectConfiguration}=require('./project_configuration.cjs');
const {createEmailOutbox}=require('./email_outbox.cjs');
const {createParkIntelligenceHandlers}=require('../functions/src/park_intelligence');
const {createTicketPromotionHandlers}=require('../functions/src/ticket_promotions');
const {createExchangeRates}=require('./exchange_rates.cjs');
const {createPasswordRecovery}=require('../functions/src/password_recovery');
const {createParkLocationHandlers}=require('../functions/src/park_locations');
const {createPrivateRecordCleanup}=require('./private_record_cleanup.cjs');
const {createReservationReminders}=require('./reservation_reminders.cjs');
const webPush=require('../functions/node_modules/web-push');
const workspaceId=require('node:crypto').createHash('sha256').update(require('node:path').resolve(__dirname,'..').toLowerCase()).digest('hex');
if(process.env.FIRESTORE_EMULATOR_HOST||process.env.FIREBASE_AUTH_EMULATOR_HOST)throw Error('The application account service must use shared Firebase.');
(async()=>{
 await accessToken();
 const configuration=createProjectConfiguration({db:sharedFirestore(),FieldValue});
 await loadServiceConfig(configuration);
 let refreshingConfiguration=false;
 const configurationTimer=setInterval(async()=>{if(refreshingConfiguration)return;refreshingConfiguration=true;try{await loadServiceConfig(configuration);}catch(_){}finally{refreshingConfiguration=false;}},60000);configurationTimer.unref();
 const reservations=createReservationHandlers({db:sharedFirestore(),FieldValue});
 const exchangeRates=createExchangeRates();
 const ticketPromotions=createTicketPromotionHandlers({db:sharedFirestore(),FieldValue,exchangeRates:exchangeRates.rates});
 const visits=createVisitHandlers({db:sharedFirestore(),FieldValue});
 const operations={'/v1/visits/check-in':visits.checkIn,'/v1/visits/rate':visits.rate};
 operations['/v1/park/exchangeRates']=exchangeRates.rates;
 for(const [name,handler]of Object.entries(ticketPromotions))operations['/v1/tickets/'+name]=handler;
 const groups=createGroupHandlers({db:sharedFirestore(),FieldValue});
 for(const [name,handler]of Object.entries(groups))operations['/v1/groups/'+name]=handler;
 const ai=new PythonWorker(),photos=createPhotoHandlers({db:sharedFirestore(),FieldValue,ai,mailReady});
 const reminders=createReservationReminders({db:sharedFirestore(),FieldValue,webPush});
 await reminders.ready();
 for(const name of ['settings','register','unregister','preference'])operations['/v1/reminders/'+name]=reminders[name];
 let remindersRunning=false;
 const reminderTimer=setInterval(async()=>{if(remindersRunning)return;remindersRunning=true;try{await reminders.processDue();}catch(_){}finally{remindersRunning=false;}},15000);reminderTimer.unref();
 const locations=createParkLocationHandlers({db:sharedFirestore(),ai,venue:require('../config/venue.json')});
 for(const [name,handler]of Object.entries(locations))operations['/v1/location/'+name]=handler;
 const intelligence=createParkIntelligenceHandlers({db:sharedFirestore(),FieldValue,ai});
 for(const [name,handler]of Object.entries(intelligence))operations['/v1/ai/'+name]=handler;
 for(const [name,handler]of Object.entries(photos))if(name!=='runMatchingJobs')operations['/v1/photos/'+name]=handler;
 const management=createParkManagementHandlers({db:sharedFirestore(),FieldValue});
 for(const [name,handler]of Object.entries(management))if(name!=='runWeather')operations['/v1/park/'+name]=handler;
 let weatherRunning=false;
 const weatherTimer=setInterval(async()=>{if(weatherRunning)return;weatherRunning=true;try{await management.runWeather();}catch(_){}finally{weatherRunning=false;}},60000);weatherTimer.unref();
 const queueJobs=createQueueJobs({db:sharedFirestore(),FieldValue});let queueRunning=false;
 const queueTimer=setInterval(async()=>{if(queueRunning)return;queueRunning=true;try{await queueJobs.processNoShows();}catch(_){}finally{queueRunning=false;}},60000);queueTimer.unref();
 const mail=createEmailOutbox({db:sharedFirestore(),FieldValue,ai,mailReady});let mailRunning=false;
 const mailTimer=setInterval(async()=>{if(mailRunning)return;mailRunning=true;try{await mail.run();}catch(_){}finally{mailRunning=false;}},15000);mailTimer.unref();
 let matching=false;
 const matchingTimer=setInterval(async()=>{if(matching)return;matching=true;try{await photos.runMatchingJobs();}catch(_){}finally{matching=false;}},10000);matchingTimer.unref();
 const recovery=createPasswordRecovery({db:sharedFirestore(),auth,mailReady,deliver:data=>ai.call('send_reset_email',data)});
 const cleanup=createPrivateRecordCleanup({db:sharedFirestore()});let cleaning=false;
 const cleanupTimer=setInterval(async()=>{if(cleaning)return;cleaning=true;try{await cleanup();}catch(_){}finally{cleaning=false;}},60000);cleanupTimer.unref();
 const server=createAccountService({auth,db,projectId,workspaceId,reservations,operations,recovery}).server();
 server.on('close',()=>{clearInterval(configurationTimer);clearInterval(reminderTimer);clearInterval(matchingTimer);clearInterval(weatherTimer);clearInterval(queueTimer);clearInterval(mailTimer);clearInterval(cleanupTimer);ai.close();});
 server.on('error',()=>{console.error('Account service could not start. Check whether port 8787 is already in use.');process.exitCode=1;});
 server.listen(8787,'127.0.0.1',()=>console.log('Account services ready at http://127.0.0.1:8787 using '+projectId));
})().catch(()=>{console.error('Account service needs Firebase CLI sign-in and access to themeparksmartmanagement.');process.exitCode=1;});
